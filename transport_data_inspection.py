import pandas as pd
import os

files = [f for f in os.listdir("/content") if f.lower().endswith(".csv")]

print(files)

import pandas as pd

df = pd.read_csv("/content/transport_datawarehouse.csv")

print("Dataset loaded successfully!")
print("Rows and columns:", df.shape)

df.head()

print(df.shape)
print(df.columns.tolist())

print("Missing values:", df.isnull().sum().sum())
print("Duplicate rows:", df.duplicated().sum())

missing = df.isnull().sum()
print(missing[missing > 0])

df.loc[
    df.isnull().any(axis=1),
    ['Reporting Period',
     'Overground Journeys (m)',
     'London Cable Car Journeys (m)',
     'TfL Rail Journeys (m)']
].head(15)

print(df[['Period beginning', 'Period ending']].head())

print("\nColumn data types:")
print(df.dtypes)

df['Period beginning'] = pd.to_datetime(
    df['Period beginning'], format='%d-%b-%y'
)

df['Period ending'] = pd.to_datetime(
    df['Period ending'], format='%d-%b-%y'
)

print(df[['Period beginning', 'Period ending']].dtypes)
print(df[['Period beginning', 'Period ending']].head())

print("Earliest reporting date:", df['Period beginning'].min())
print("Latest reporting date:", df['Period ending'].max())

print("Invalid date ranges:",
      (df['Period beginning'] > df['Period ending']).sum())

print("Missing start dates:", df['Period beginning'].isnull().sum())
print("Missing end dates:", df['Period ending'].isnull().sum())

journey_cols = df.columns[
    df.columns.str.contains('Journeys')
]

print("Negative journey values:")
print((df[journey_cols] < 0).sum())

print("\nJourney value summary:")
print(df[journey_cols].describe().round(2))

journey_cols = [
    'Bus journeys (m)',
    'Underground journeys (m)',
    'DLR Journeys (m)',
    'Tram Journeys (m)',
    'Overground Journeys (m)',
    'London Cable Car Journeys (m)',
    'TfL Rail Journeys (m)'
]

print("Negative values per transport mode:")
print((df[journey_cols] < 0).sum())

print("\nMissing values per transport mode:")
print(df[journey_cols].isnull().sum())

transport_long = df.melt(
    id_vars=[
        'Period and Financial year',
        'Reporting Period',
        'Days in period',
        'Period beginning',
        'Period ending'
    ],
    value_vars=journey_cols,
    var_name='Transport Mode',
    value_name='Journeys (millions)'
)

print("Transformed shape:", transport_long.shape)
transport_long.head(10)

print("Rows per transport mode:")
print(transport_long.groupby('Transport Mode').size())

print("\nMissing journey values:")
print(transport_long['Journeys (millions)'].isnull().sum())

print("\nDuplicate rows:")
print(transport_long.duplicated().sum())

transport_long.to_csv(
    'transport_journeys_transformed.csv',
    index=False
)

print("Transformed dataset exported successfully!")